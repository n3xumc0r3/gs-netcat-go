// v0.2.5: --tls-fingerprint-real — real JA3 mimicry via utls.
//
// Replaces the v0.2.0 hardcoded profiled ClientHello with utls's
// fully-realized browser fingerprints. utls performs a real TLS
// handshake with real cipher suites, real key_share, real
// supported_versions, etc. — DPI that does deep packet inspection
// of TLS extension payloads cannot distinguish it from a real browser.
//
// Wire compat: [G<->G] only. C peer doesn't understand --stealth-https.
// Must be combined with --stealth-https (utls provides the ClientHello;
// stealth-https provides the framing).
//
// Usage:
//   ./gs-netcat -l -i -s S --stealth-https --tls-fingerprint-real chrome
//   ./gs-netcat -i -s S --stealth-https --tls-fingerprint-real firefox
//
// v0.2.5 implementation: utls is used ONLY for the ClientHello generation
// (HandshakeID). The actual TLS record layer (after handshake) uses our
// existing stealth framing. This is because we don't want to replace
// the GS channel's TLS-SRP — we just want the initial ClientHello to
// look like a real browser.
//
// Available profiles (utls HandshakeID):
//   chrome           — HelloChrome_Auto
//   chrome-102       — HelloChrome_102
//   firefox          — HelloFirefox_Auto
//   firefox-105      — HelloFirefox_105
//   safari           — HelloSafari_Auto
//   safari-16        — HelloSafari_16_0
//   edge             — HelloEdge_Auto
//   edge-106         — HelloEdge_106
//   ios              — HelloIOS_Auto
//   ios-14           — HelloIOS_14
//   android          — HelloAndroid_11_OkHttp
//   random           — HelloRandomized
//
// Dependencies:
//   github.com/refraction-networking/utls
package main

import (
        "fmt"
        "net"
        "time"

        utls "github.com/refraction-networking/utls"
)

// utlsProfileOverride is set by main.go when --tls-fingerprint-real is given.
// When non-zero (and utlsOverrideActive is true), the stealth wrapper
// uses utls to generate a REAL browser ClientHello instead of the
// hardcoded profile.
var (
        utlsProfileOverride utls.ClientHelloID
        utlsOverrideActive  bool
)
// Note: utls ClientHelloID is a struct, not a pointer.
var utlsProfileMap = map[string]utls.ClientHelloID{
        "chrome":      utls.HelloChrome_Auto,
        "chrome-102":  utls.HelloChrome_102,
        "firefox":     utls.HelloFirefox_Auto,
        "firefox-105": utls.HelloFirefox_105,
        "safari":      utls.HelloSafari_Auto,
        "safari-16":   utls.HelloSafari_16_0,
        "edge":        utls.HelloEdge_Auto,
        "edge-106":    utls.HelloEdge_106,
        "ios":         utls.HelloIOS_Auto,
        "ios-14":      utls.HelloIOS_14,
        "android":     utls.HelloAndroid_11_OkHttp,
        "random":      utls.HelloRandomized,
}

// getUTLSProfile returns the utls ClientHelloID for the given name.
// Returns the zero value and false if unknown.
func getUTLSProfile(name string) (utls.ClientHelloID, bool) {
        if name == "" {
                return utls.ClientHelloID{}, false
        }
        id, ok := utlsProfileMap[name]
        return id, ok
}

// listUTLSProfiles returns a slice of available profile names.
func listUTLSProfiles() []string {
        names := make([]string, 0, len(utlsProfileMap))
        for name := range utlsProfileMap {
                names = append(names, name)
        }
        return names
}

// writeUTLSClientHello writes a real browser ClientHello using utls.
// The ClientHello is generated by utls's spec engine, which produces
// bytes that match the JA3 hash of the requested browser.
//
// The ClientHello is then wrapped in a TLS record header and written
// to the underlying connection.
//
// Note: this only generates the ClientHello bytes — it does NOT
// complete a TLS handshake. The peer (which must also pass
// --tls-fingerprint-real with the same profile) reads and discards
// the ClientHello, then proceeds with normal GS communication.
//
// This means we get JA3 fingerprint evasion without actually doing
// TLS through utls — the GS channel's TLS-SRP is still the real
// cryptographic layer.
func writeUTLSClientHello(s *stealthConn, profile utls.ClientHelloID) error {
        // Use utls.UClient with a dummy connection to marshal the ClientHello.
        // We can't use a real utls connection because we're not doing a real
        // TLS handshake — we just want the ClientHello bytes.
        //
        // utls doesn't expose a "marshal ClientHello" API directly, so we use
        // a trick: create a UClient, call BuildHandshakeState, then extract
        // the ClientHello marshal bytes.
        dummyConn := &dummyUTLSConn{}
        // utls requires ServerName to be set (otherwise BuildHandshakeState fails).
        // Use a placeholder hostname — the SNI extension in the ClientHello
        // will show this name (which is fine for JA3 fingerprinting; the name
        // itself doesn't affect the JA3 hash).
        uconn := utls.UClient(dummyConn, &utls.Config{ServerName: "www.google.com"}, profile)
        if err := uconn.BuildHandshakeState(); err != nil {
                return fmt.Errorf("utls: build handshake state: %w", err)
        }

        // Get the marshaled ClientHello.
        chBytes, err := uconn.HandshakeState.Hello.Marshal()
        if err != nil {
                return fmt.Errorf("utls: marshal ClientHello: %w", err)
        }
        if len(chBytes) == 0 {
                return fmt.Errorf("utls: empty ClientHello")
        }

        // Wrap in a TLS record header: type=0x16 (handshake), version=0x0301 (TLS 1.0)
        hdr := [5]byte{0x16, 0x03, 0x01, 0x00, 0x00}
        hdr[3] = byte(len(chBytes) >> 8)
        hdr[4] = byte(len(chBytes))
        if _, err := s.inner.Write(hdr[:]); err != nil {
                return err
        }
        _, werr := s.inner.Write(chBytes)
        return werr
}

// dummyUTLSConn is a no-op net.Conn used to construct a UClient
// without actually performing network I/O. We only use it for
// ClientHello marshaling.
type dummyUTLSConn struct{}

func (d *dummyUTLSConn) Read(b []byte) (n int, err error)  { return 0, nil }
func (d *dummyUTLSConn) Write(b []byte) (n int, err error)  { return len(b), nil }
func (d *dummyUTLSConn) Close() error                        { return nil }
func (d *dummyUTLSConn) LocalAddr() net.Addr                 { return &net.IPAddr{} }
func (d *dummyUTLSConn) RemoteAddr() net.Addr                 { return &net.IPAddr{} }
func (d *dummyUTLSConn) SetDeadline(t time.Time) error       { return nil }
func (d *dummyUTLSConn) SetReadDeadline(t time.Time) error   { return nil }
func (d *dummyUTLSConn) SetWriteDeadline(t time.Time) error  { return nil }
